def update_locale(lang_code, data):
    """Apply replacements and add assessment keys to a locale dict."""
    # 1. Apply EN simplified values as baseline for keys still containing jargon
    for key, new_val in EN.items():
        if key in data:
            data[key] = new_val

    # 2. Apply language-specific overrides (these override step 1)
    if lang_code in OVERRIDES:
        for key, new_val in OVERRIDES[lang_code].items():
            if key in data:
                data[key] = new_val

    # 3. Add assessment keys (insert after 'onboardingScienceIISc' if possible, else at end)
    if lang_code in ASSESSMENT:
        akeys = ASSESSMENT[lang_code]
        if "assessmentTitle" not in data:
            # Rebuild dict inserting assessment keys after 'onboardingScienceIISc'
            new_data = {}
            inserted = False
            for k, v in data.items():
                new_data[k] = v
                if k == "onboardingScienceIISc" and not inserted:
                    for ak, av in akeys.items():
                        new_data[ak] = av
                    inserted = True
            if not inserted:
                for ak, av in akeys.items():
                    new_data[ak] = av
            return new_data
    return data

def main():
    locales = ['en', 'tr', 'ar', 'de', 'es', 'fa', 'fi', 'fr', 'hi', 'it', 'ja', 'ko', 'nl', 'pt-BR', 'zh']
    for lang in locales:
        path = os.path.join(LOCALES_DIR, f'{lang}.json')
        if not os.path.exists(path):
            print(f'SKIP {lang}: file not found')
            continue
        with open(path, encoding='utf-8') as f:
            data = json.load(f)
        updated = update_locale(lang, data)
        with open(path, 'w', encoding='utf-8') as f:
            json.dump(updated, f, ensure_ascii=False, indent=2)
        print(f'OK {lang}')

if __name__ == '__main__':
    main()
